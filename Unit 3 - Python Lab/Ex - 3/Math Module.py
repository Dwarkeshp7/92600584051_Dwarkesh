# 3. Write a program to perform mathematical operations using math module.

import math

# 1. Using Mathematical Constants
print("--- Constants ---")
print("Value of Pi (π):", math.pi)
print("Value of Euler's Number (e):", math.e)

# 2. Power and Logarithmic Operations
print("\n--- Power & Logarithms ---")
print("Square root of 64:", math.sqrt(64))
print("2 raised to the power of 5:", math.pow(2, 5))
 
# 3. Numeric & Rounding Operations
print("\n--- Numeric & Rounding ---")
print("Ceiling of 4.3 (rounds up):", math.ceil(4.3))
print("Floor of 4.7 (rounds down):", math.floor(4.7))
print("Absolute value of -15.5:", math.fabs(-15.5))
print("Factorial of 5 (5!):", math.factorial(5))

